def collect_delta_sf(bin_tag, series_name):
    b = BASELINE.get(bin_tag, {}).get(series_name)
    i = ISRFSR.get(bin_tag, {}).get(series_name)
    if not b or not i:
        return None
    #endif
    xb, yb, eb = to_series(b)
    xi, yi, ei = to_series(i)
    assert_same_length(bin_tag, series_name, xb, xi)
    d, ed = delta(yb, eb, yi, ei)
    return xb, yb, eb, yi, ei, d, ed

def collect_delta_dilution(bin_tag, x_ref):
    db = DILUTION_BASELINE.get(bin_tag)
    di = DILUTION_ISRFSR.get(bin_tag)
    if not db or not di:
        return None
    #endif
    db = np.array(db, dtype=float)
    di = np.array(di, dtype=float)
    n = min(len(db), len(di), len(x_ref))
    x = x_ref[:n]
    yb, eb = db[:n, 0], db[:n, 1]
    yi, ei = di[:n, 0], di[:n, 1]
    d, ed = delta(yb, eb, yi, ei)
    return x, yb, eb, yi, ei, d, ed

