def to_series(triples, negate_x=True, sort=True):
    """Convert list-of-[x,y,e] to aligned numpy arrays; optionally negate x (to get -t')."""
    arr = np.array(triples, dtype=float)
    x = -arr[:, 0] if negate_x else arr[:, 0]
    y = arr[:, 1]
    e = arr[:, 2]
    if sort:
        idx = np.argsort(x)
        x, y, e = x[idx], y[idx], e[idx]
    return x, y, e

def delta(yb, eb, yi, ei):
    """Baseline − ISR&FSR with uncorrelated error propagation."""
    d = yb - yi
    ed = np.sqrt(eb**2 + ei**2)
    return d, ed

def assert_same_length(bin_tag, series_name, xb, xi):
    if len(xb) != len(xi):
        raise ValueError(
            f"[ERROR] Bin={bin_tag} Series={series_name}: "
            f"mismatched counts (Baseline {len(xb)} vs ISR&FSR {len(xi)})."
        )

def dilution_series(bin_tag, which, x_fallback):
    if which == "Baseline":
        d = DILUTION_BASELINE.get(bin_tag)
    else:
        d = DILUTION_ISRFSR.get(bin_tag)
    if d is None:
        return None
    arr = np.array(d, dtype=float)
    n = min(len(arr), len(x_fallback))
    x = x_fallback[:n]
    y = arr[:n, 0]
    e = arr[:n, 1]
    return x, y, e

def get_bin_title(bin_tag):
    return r"$ep \rightarrow en\pi^{+}$ — " + XB_LABELS.get(bin_tag, bin_tag) + " — Baseline vs Data-driven ISR \\& FSR"

