    db = np.array(db, dtype=float)
    di = np.array(di, dtype=float)
    n = min(len(db), len(di), len(x_ref))
    x = x_ref[:n]
    yb, eb = db[:n, 0], db[:n, 1]
    yi, ei = di[:n, 0], di[:n, 1]
    yd, ed = delta(yb, eb, yi, ei)
    ax.errorbar(
        x, yd, yerr=ed,
        fmt="o", color="k", ecolor="k",
        capsize=CAPSIZE, markersize=MS, linestyle="None"
    )
    ax.set(xlim=XLIM_T, ylim=YLIM_DELTA, xlabel=X_LABEL, ylabel=r"$\Delta D_{f}$")
    ax.axhline(0, color="black", linestyle="--", linewidth=1.2)
    ax.grid(True, linestyle="--", alpha=0.6)

