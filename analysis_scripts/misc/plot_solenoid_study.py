def to_series(triples):
    """Convert [(t,value,err),...] with negative t into dict(x=-t, y, yerr), sorted by x."""
    arr = np.asarray(triples, dtype=float)
    x = -arr[:, 0]
    y = arr[:, 1]
    e = arr[:, 2]
    order = np.argsort(x)
    return {"x": x[order], "y": y[order], "yerr": e[order]}
#endfor

def add_component(ax, neg1, pos1, ylabel, ylim):
    sA = to_series(neg1)
    sB = to_series(pos1)

    ax.errorbar(sA["x"], sA["y"], yerr=sA["yerr"], fmt="o", ms=4,
                color="tab:blue", ecolor="tab:blue", capsize=3, label="solenoid = −1")
    ax.errorbar(sB["x"], sB["y"], yerr=sB["yerr"], fmt="s", ms=4,
                color="tab:orange", ecolor="tab:orange", capsize=3, label="solenoid = +1")

    ax.set_xlim(0.0, 1.30)
    ax.set_ylim(*ylim)
    ax.set_xlabel(r"$-t\ \mathrm{(GeV^{2})}$")
    ax.set_ylabel(ylabel)
    ax.axhline(0.0, color="black", linestyle="--", linewidth=1.0)
    ax.grid(True, linestyle="--", alpha=0.6)
    ax.legend(frameon=True, edgecolor="black", fontsize=10)
#endfor

# ─────────────────────────────────────────────────────────────────────
