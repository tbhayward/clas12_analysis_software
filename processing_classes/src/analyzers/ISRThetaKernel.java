  // Keep them together for easy bin lookup
  private static final double[][] CDFS = new double[][]{
      CDF_E0_1, CDF_E1_2, CDF_E2_3, CDF_E3_4, CDF_E4_10
  };

  private ISRThetaKernel() {}

  /** Return θ (radians) sampled from the appropriate CDF for this Egamma (GeV). */
  public static double sampleThetaRad(double EgammaGeV) {
    final double[] cdf = chooseCDF(EgammaGeV);

    // Draw a uniform u in [0,1)
    final double u = ThreadLocalRandom.current().nextDouble();

    // Inverse-CDF via binary search: find first index with cdf[idx] >= u
    int idx = Arrays.binarySearch(cdf, u);
    if (idx < 0) idx = -idx - 1;
    if (idx <= 0) idx = 0;
    if (idx >= cdf.length) idx = cdf.length - 1;

    // Uniform-in-bin refinement between theta_edges[idx] and theta_edges[idx+1]
    final double thLoDeg = THETA_EDGES_DEG[idx];
    final double thHiDeg = THETA_EDGES_DEG[idx + 1];
    final double u2 = ThreadLocalRandom.current().nextDouble();
    final double thDeg = thLoDeg + (thHiDeg - thLoDeg) * u2;

    return Math.toRadians(thDeg);
  }

  /** Choose the Egamma bin: [0,1), [1,2), [2,3), [3,4), [4,10]. */
  private static double[] chooseCDF(double EgammaGeV) {
    if (EgammaGeV < 1.0) return CDF_E0_1;
    if (EgammaGeV < 2.0) return CDF_E1_2;
    if (EgammaGeV < 3.0) return CDF_E2_3;
    if (EgammaGeV < 4.0) return CDF_E3_4;
    // Clamp very large Egamma to the last bin
    return CDF_E4_10;
  }

  /** Optional sanity check to call once at startup. */
  public static void assertMonotoneAndUnit() {
    for (double[] cdf : CDFS) {
      double prev = 0.0;
      for (double v : cdf) {
        if (v + 1e-12 < prev) throw new IllegalStateException("CDF not monotone");
        prev = v;
      }
      double last = cdf[cdf.length - 1];
      if (Math.abs(last - 1.0) > 1e-6)
        throw new IllegalStateException("CDF last entry != 1.0 (was " + last + ")");
    }
    if (THETA_EDGES_DEG.length != CDFS[0].length + 1)
      throw new IllegalStateException("theta edges length mismatch");
  }
